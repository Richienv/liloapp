  reviewed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

comment on table public.streamer_verification_submissions is 'KYC submissions from streamers: identity documents, a selfie, and proof of their TikTok/Shopee Live account. An admin reviews each row and mirrors the outcome onto streamers.verification_status.';
comment on column public.streamer_verification_submissions.id_card_url is 'Storage path inside the private verification_documents bucket, always prefixed with the owning user_id.';
comment on column public.streamer_verification_submissions.status is 'pending (awaiting review), approved, or rejected. Only admins may move it off pending.';
comment on column public.streamer_verification_submissions.notes is 'Reviewer notes. Doubles as the rejection explanation shown back to the streamer.';

do $$
