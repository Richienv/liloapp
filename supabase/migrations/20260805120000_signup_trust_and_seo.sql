-- Migration: Signup trust & SEO foundations (schema contract v1)
--
-- Purpose:
--   1. Give every streamer a stable, unique, URL-safe `username` so the public
--      profile can live at `/[username]` and appear in sitemap.xml.
--   2. Introduce an explicit trust pipeline (`verification_status`,
--      `is_active`, KYC submissions, payout accounts) so a brand only ever sees
--      streamers Salda has actually vetted.
--   3. Replace free-text `location` with a canonical `city_slug` drawn from the
--      30-city registry in `lib/cities.ts`, which powers `/location/<slug>` SEO
--      pages and shipping logistics.
--
-- Affected objects:
--   - public.streamers                          (new columns + indexes + backfill)
--   - public.users                              (new columns + backfill)
--   - public.streamer_verification_submissions  (new table)
--   - public.streamer_payout_accounts           (new table)
--   - public.is_admin()                         (new helper function)
--   - public.salda_set_updated_at()             (new trigger function)
--   - storage.buckets / storage.objects         (new private bucket + policies)
--
-- Special considerations:
--   - The production database has live rows. Every step below is written to be
--     safely re-runnable and to keep currently-bookable streamers bookable; see
--     the GRANDFATHERING note in section 3.
--   - New tables enable Row Level Security and grant nothing to `anon`: KYC
--     documents and bank accounts must never be readable with the public key.
--   - Admin access mirrors `app/admin/layout.tsx`, which uses an email
--     allowlist; see section 1 for how that allowlist reaches the database.


-- ============================================================================
-- 1) ADMIN IDENTIFICATION
--
-- `app/admin/layout.tsx` has no admin role in the data model (users.user_type
-- is only 'client' | 'streamer'), so it gates /admin on a comma-separated
-- ADMIN_EMAILS environment variable. Postgres cannot read a Next.js env var, so
-- the same allowlist is mirrored into a database setting and compared against
-- the caller's JWT email. Fail-closed, exactly like the app: an unset setting
-- means nobody is an admin.
--
-- SET THIS AFTER APPLYING THE MIGRATION (values must match ADMIN_EMAILS):
--   alter database postgres set app.admin_emails = 'owner@salda.id,ops@salda.id';
--   -- then reconnect, or `select pg_reload_conf();`
--
-- Server code that runs with the service-role key (utils/supabase/admin.ts)
-- bypasses RLS entirely and does not depend on this setting.
-- ============================================================================

-- security definer on purpose: this runs inside RLS policies, so it must not
-- depend on the caller holding privileges on the auth schema. If it raised
-- "permission denied for schema auth" instead of returning false, every policy
-- that calls it would error out and a streamer would lose access to their own
-- rows. It reads no tables and takes no arguments, so there is nothing an
-- attacker can steer.
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from
      unnest(
        string_to_array(
          lower(coalesce(current_setting('app.admin_emails', true), '')),
          ','
        )
      ) as allowlist (email)
    where
      btrim(allowlist.email) <> ''
    and
      btrim(allowlist.email) = lower(coalesce(auth.jwt() ->> 'email', ''))
  );
$$;

comment on function public.is_admin() is 'True when the caller''s JWT email appears in the app.admin_emails database setting. Database mirror of the ADMIN_EMAILS allowlist enforced by app/admin/layout.tsx. Fail-closed: returns false when the setting is unset.';

grant execute on function public.is_admin() to anon, authenticated, service_role;


