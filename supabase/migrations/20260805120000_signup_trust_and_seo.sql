-- only ever be reachable through a signed URL.
--
-- PATH CONVENTION (enforced by the policies below):
--   verification_documents/<auth.uid()>/<filename>
-- The first path segment must be the uploader's user id; anything else is
-- rejected on insert and invisible on read.
-- ============================================================================

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'verification_documents',
  'verification_documents',
  false,
  10485760,
  array['image/jpeg', 'image/png', 'image/webp', 'application/pdf']
)
on conflict (id) do update
set public = excluded.public,
    file_size_limit = excluded.file_size_limit,
    allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "verification_documents_insert_own_prefix" on storage.objects;
create policy "verification_documents_insert_own_prefix"
  on storage.objects
  for insert
  to authenticated
  with check (
    bucket_id = 'verification_documents'
    and (storage.foldername(name))[1] = auth.uid()::text
  );

drop policy if exists "verification_documents_select_own_prefix" on storage.objects;
create policy "verification_documents_select_own_prefix"
  on storage.objects
  for select
  to authenticated
  using (
    bucket_id = 'verification_documents'
    and (storage.foldername(name))[1] = auth.uid()::text
  );

drop policy if exists "verification_documents_update_own_prefix" on storage.objects;
create policy "verification_documents_update_own_prefix"
  on storage.objects
  for update
  to authenticated
  using (
    bucket_id = 'verification_documents'
    and (storage.foldername(name))[1] = auth.uid()::text
  )
  with check (
    bucket_id = 'verification_documents'
    and (storage.foldername(name))[1] = auth.uid()::text
  );

drop policy if exists "verification_documents_select_admin" on storage.objects;
create policy "verification_documents_select_admin"
  on storage.objects
  for select
  to authenticated
  using (
    bucket_id = 'verification_documents'
    and public.is_admin()
  );

