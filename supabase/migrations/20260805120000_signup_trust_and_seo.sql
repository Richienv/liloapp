set city_slug = public.salda_resolve_city_slug(location)
where city_slug is null
  and location is not null
  and public.salda_resolve_city_slug(location) is not null;

update public.users
set city_slug = public.salda_resolve_city_slug(location)
where city_slug is null
  and location is not null
  and public.salda_resolve_city_slug(location) is not null;

