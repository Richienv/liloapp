-- No policy is granted to `anon`. Identity documents must be unreachable with
-- the public browser key, and an absent policy denies by default.

drop policy if exists "verification_submissions_select_own" on public.streamer_verification_submissions;
create policy "verification_submissions_select_own"
  on public.streamer_verification_submissions
  for select
  to authenticated
  using (
    streamer_id in (select id from public.streamers where user_id = auth.uid())
  );

drop policy if exists "verification_submissions_select_admin" on public.streamer_verification_submissions;
create policy "verification_submissions_select_admin"
  on public.streamer_verification_submissions
  for select
  to authenticated
  using (public.is_admin());

drop policy if exists "verification_submissions_insert_own" on public.streamer_verification_submissions;
create policy "verification_submissions_insert_own"
  on public.streamer_verification_submissions
  for insert
  to authenticated
  with check (
    user_id = auth.uid()
    and streamer_id in (select id from public.streamers where user_id = auth.uid())
    and status = 'pending'
  );

drop policy if exists "verification_submissions_update_own_pending" on public.streamer_verification_submissions;
create policy "verification_submissions_update_own_pending"
  on public.streamer_verification_submissions
  for update
  to authenticated
  using (
    status = 'pending'
    and streamer_id in (select id from public.streamers where user_id = auth.uid())
  )
  with check (
    status = 'pending'
    and streamer_id in (select id from public.streamers where user_id = auth.uid())
  );

drop policy if exists "verification_submissions_update_admin" on public.streamer_verification_submissions;
create policy "verification_submissions_update_admin"
  on public.streamer_verification_submissions
  for update
  to authenticated
  using (public.is_admin())
  with check (public.is_admin());

