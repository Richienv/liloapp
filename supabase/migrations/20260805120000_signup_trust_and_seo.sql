-- 11) STREAMER PAYOUT ACCOUNTS
--
-- Where Salda sends a streamer's earnings. Separate table because a streamer
-- may rotate accounts over time and the history matters for reconciliation.
-- ============================================================================

create table if not exists public.streamer_payout_accounts (
  id uuid primary key default gen_random_uuid(),
  streamer_id bigint not null references public.streamers (id) on delete cascade,
  bank_code text not null,
  bank_name text not null,
  account_number text not null,
  account_holder_name text not null,
  is_primary boolean not null default true,
  verified_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

comment on table public.streamer_payout_accounts is 'Bank accounts a streamer can be paid out to. At most one row per streamer may be primary; that is the account used for automatic disbursement.';
comment on column public.streamer_payout_accounts.bank_code is 'Bank identifier used by the disbursement provider (e.g. bca, mandiri, bni, bri).';
comment on column public.streamer_payout_accounts.verified_at is 'Set when the account holder name has been confirmed against the bank. Should only be written server-side, after a name check.';

create index if not exists idx_streamer_payout_accounts_streamer
  on public.streamer_payout_accounts (streamer_id);

-- Partial unique index: a streamer may keep several accounts on file but only
-- one of them can be flagged primary, so payouts always have one destination.
create unique index if not exists idx_streamer_payout_accounts_one_primary
  on public.streamer_payout_accounts (streamer_id)
  where is_primary;

drop trigger if exists set_updated_at on public.streamer_payout_accounts;
create trigger set_updated_at
  before update on public.streamer_payout_accounts
  for each row
  execute function public.salda_set_updated_at();

alter table public.streamer_payout_accounts enable row level security;

