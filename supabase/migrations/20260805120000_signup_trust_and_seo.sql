-- ============================================================================
-- 3) STREAMERS: VERIFICATION STATUS (+ GRANDFATHERING)
--
-- The column is added and backfilled inside one guarded block so the backfill
-- runs exactly once — on the run that creates the column. Re-running this
-- migration must never reset a streamer an admin has since rejected or
-- suspended back to 'approved'.
-- ============================================================================

do $$
declare
  column_already_existed boolean;
begin
  select exists (
    select 1
    from information_schema.columns
    where table_schema = 'public'
      and table_name = 'streamers'
      and column_name = 'verification_status'
  )
  into column_already_existed;

  if not column_already_existed then
    alter table public.streamers
      add column verification_status text not null default 'pending';

    /*
      GRANDFATHERING — read this before changing it.

      Every streamer that already exists is marked 'approved' with
      verified_at = now(). This is deliberate: the new default 'pending' must
      apply only to NEW signups, otherwise every currently-bookable streamer
      would vanish the moment this ships.

      verified_by is deliberately left null — no admin actually reviewed these
      rows, and recording a fake reviewer would poison the audit trail.
    */
    update public.streamers
    set verification_status = 'approved',
        verified_at = coalesce(verified_at, now());
  end if;
end;
$$;

comment on column public.streamers.verification_status is 'Trust state of the streamer: pending (new signup, awaiting review), approved (bookable), rejected (failed review), suspended (previously approved, revoked). Rows that predate this column were grandfathered to approved.';

-- The CHECK is added after the backfill so the backfill can never be blocked by
-- a value it is itself about to write.
do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conrelid = 'public.streamers'::regclass
      and conname = 'streamers_verification_status_check'
  ) then
    alter table public.streamers
      add constraint streamers_verification_status_check
      check (verification_status in ('pending', 'approved', 'rejected', 'suspended'));
  end if;
end;
$$;


-- ============================================================================
-- 4) STREAMERS: USERNAME BACKFILL
--
-- Two passes, both idempotent, both mirroring the rules in lib/username.ts
-- (lowercase, [a-z0-9_-], must start and end alphanumeric, 3-30 chars, not a
-- reserved route name):
--   4a. Resolve any pre-existing case-insensitive duplicates, which would
--       otherwise make the unique index in section 5 impossible to create.
--   4b. Assign a username to every row that has none.
-- The unique index is created only AFTER both passes have run.
-- ============================================================================

do $$
declare
  -- Mirror of RESERVED_USERNAMES in lib/username.ts. Each of these already
  -- resolves to a real route, so a streamer must never be able to hold one.
  reserved_usernames text[] := array[
    'admin', 'api', 'auth', 'booking-detail', 'client-bookings',
    'forgot-password', 'location', 'locations', 'messages', 'notifications',
    'privacy-notice', 'protected', 'reset-password', 'settings', 'sign-in',
    'sign-up', 'sitemap', 'streamer-dashboard', 'streamer-schedule',
    'streamer-sign-up', 'streamers', 'terms', 'tutorial', 'robots', 'salda',
    'support', 'help', 'about', 'contact', 'me', 'new', 'null', 'undefined'
  ];
  streamer record;
  stem text;
  candidate text;
  attempt integer;
begin
  /*
    4a. Duplicate resolution.

    Only rows that already carry a username are touched, and the lowest id
    keeps its value untouched — it is the oldest, most likely to be linked
    from the outside. Later duplicates are re-suffixed, which does change a
    live URL, but a case-insensitively unique username is a hard requirement
    for /[username] routing and there is no other way to reconcile them.
  */
  for streamer in
    select duplicates.id, duplicates.username
    from (
      select
        streamers.id,
        streamers.username,
        row_number() over (
          partition by lower(streamers.username)
          order by streamers.id
        ) as occurrence
      from public.streamers
      where streamers.username is not null
        and btrim(streamers.username) <> ''
    ) as duplicates
    where duplicates.occurrence > 1
    order by duplicates.id
  loop
    stem := regexp_replace(lower(btrim(streamer.username)), '[_-]+$', '');
    if length(stem) < 3 then
      stem := 'streamer-' || streamer.id::text;
    end if;

    attempt := 1;
    candidate := stem;
    while candidate = any (reserved_usernames)
       or exists (
            select 1
            from public.streamers
            where lower(public.streamers.username) = candidate
              and public.streamers.id <> streamer.id
          )
    loop
      attempt := attempt + 1;
      -- withSuffix() from lib/username.ts: trim the stem so the suffixed
      -- username still fits in 30 characters, then append "-<n>".
      candidate := regexp_replace(
        left(stem, 30 - length('-' || attempt::text)),
        '[_-]+$', ''
      ) || '-' || attempt::text;
    end loop;

    update public.streamers
    set username = candidate
    where public.streamers.id = streamer.id;
  end loop;

  /*
    4b. Assignment for rows with no username.

    The stem is slugifyUsername(first_name + ' ' + last_name) ported to SQL.
    When the name yields fewer than 3 usable characters (empty, emoji-only,
    initials) the row falls back to `streamer-<id>`: unlike lib/username.ts's
    generic "streamer-baru" stem, the id is already unique, so the fallback
    does not force every unnamed row through the collision loop.
  */
  for streamer in
    select
      streamers.id,
      streamers.first_name,
      streamers.last_name
    from public.streamers
    where streamers.username is null
       or btrim(streamers.username) = ''
    order by streamers.id
  loop
    -- Strip accents, then apply the same transformations as slugifyUsername().
    stem := lower(
      translate(
        coalesce(streamer.first_name, '') || ' ' || coalesce(streamer.last_name, ''),
        'áàâäãåéèêëíìîïóòôöõúùûüñçÁÀÂÄÃÅÉÈÊËÍÌÎÏÓÒÔÖÕÚÙÛÜÑÇ',
        'aaaaaaeeeeiiiiooooouuuuncAAAAAAEEEEIIIIOOOOOUUUUNC'
      )
    );
    stem := regexp_replace(stem, '[^a-z0-9_-]+', '-', 'g');
    stem := regexp_replace(stem, '-{2,}', '-', 'g');
    stem := regexp_replace(stem, '^[_-]+', '');
    stem := regexp_replace(stem, '[_-]+$', '');
    stem := left(stem, 30);
    stem := regexp_replace(stem, '[_-]+$', '');

    if length(stem) < 3 then
      stem := 'streamer-' || streamer.id::text;
    end if;

    attempt := 1;
    candidate := stem;
    while candidate = any (reserved_usernames)
       or exists (
            select 1
            from public.streamers
            where lower(public.streamers.username) = candidate
          )
    loop
      attempt := attempt + 1;
      candidate := regexp_replace(
        left(stem, 30 - length('-' || attempt::text)),
        '[_-]+$', ''
      ) || '-' || attempt::text;
    end loop;

    update public.streamers
    set username = candidate
    where public.streamers.id = streamer.id;
  end loop;
end;
$$;


